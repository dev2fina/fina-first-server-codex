package net.fina.server.dcs.uploadfile.impl.util;

public class _ExcelFileNameInfo {
	private String fiType;
	private String fiCode;
	private String returnTypeCode;
	private String periodTypeCode;
	private String firstDayOfPeriod;
	private String year;

	public String getFiType() {
		return fiType;
	}

	public void setFiType(String fiType) {
		this.fiType = fiType;
	}

	public String getFiCode() {
		return fiCode;
	}

	public void setFiCode(String fiCode) {
		this.fiCode = fiCode;
	}

	public String getReturnTypeCode() {
		return returnTypeCode;
	}

	public void setReturnTypeCode(String returnTypeCode) {
		this.returnTypeCode = returnTypeCode;
	}

	public String getPeriodTypeCode() {
		return periodTypeCode;
	}

	public void setPeriodTypeCode(String periodTypeCode) {
		this.periodTypeCode = periodTypeCode;
	}

	public String getFirstDayOfPeriod() {
		return firstDayOfPeriod;
	}

	public void setFirstDayOfPeriod(String firstDayOfPeriod) {
		this.firstDayOfPeriod = firstDayOfPeriod;
	}

	public String getYear() {
		return year;
	}

	public void setYear(String year) {
		this.year = year;
	}

}
