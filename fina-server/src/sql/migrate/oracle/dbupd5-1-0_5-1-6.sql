/*
	Create queue files table
 */
CREATE TABLE IN_UPLOADFILE_QUEUE
(
  FILE_ID NUMBER(18, 0) NOT NULL
, USER_ID NUMBER(10, 0) NOT NULL
, FILE_NAME NVARCHAR2(256) NOT NULL
, STATUS NUMBER(10, 0) NOT NULL
, CONSTRAINT IN_UPLOADFILE_QUEUE_PK PRIMARY KEY
  (
    FILE_ID
  )
 )

